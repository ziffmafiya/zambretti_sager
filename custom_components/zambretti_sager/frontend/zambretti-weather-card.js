      show_precip:    true,
      show_forecasts: true,
      auto_theme:     true,
      theme_alpha:    config.theme_alpha ?? 100,
      custom_bg:      "linear-gradient(135deg,#1565C0 0%,#1976D2 100%)",
      ...config,
